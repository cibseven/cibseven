package org.cibseven.bpm.quarkus.engine.test.spin;

import java.util.ArrayList;
import java.util.List;

/**
 * A plain bean with a constructor without parameters, read through its setters by Spin JSON.
 */
public class SpinJsonDto {

  protected String name;
  protected int amount;
  protected List<String> tags = new ArrayList<>();

  public SpinJsonDto() {
  }

  public SpinJsonDto(String name, int amount) {
    this.name = name;
    this.amount = amount;
  }

  public String getName() {
    return name;
  }

  public void setName(String name) {
    this.name = name;
  }

  public int getAmount() {
    return amount;
  }

  public void setAmount(int amount) {
    this.amount = amount;
  }

  public List<String> getTags() {
    return tags;
  }

  public void setTags(List<String> tags) {
    this.tags = tags;
  }

}

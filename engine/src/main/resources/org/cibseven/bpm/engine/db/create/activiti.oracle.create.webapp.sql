CREATE TABLE MOD_ELEMENT_TEMPLATES (
    ID VARCHAR2(36 CHAR) PRIMARY KEY,
    ACTIVE NUMBER(1) DEFAULT 1,
    VERSION NUMBER(11) DEFAULT 1,
    TEMPLATE_ID VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    NAME VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION CLOB,
    ORIGIN VARCHAR2(50 CHAR) NOT NULL,
    CONTENT CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(100 CHAR),
    UPDATED_BY VARCHAR2(100 CHAR)
);

CREATE TABLE MOD_FOLDERS (
    ID VARCHAR2(36 CHAR) NOT NULL PRIMARY KEY,
    PARENT_ID VARCHAR2(36 CHAR),
    NAME VARCHAR2(255 CHAR) NOT NULL,
    CREATED TIMESTAMP,
    CREATED_BY VARCHAR2(100 CHAR),
    UPDATED TIMESTAMP,
    UPDATED_BY VARCHAR2(100 CHAR),
    CONSTRAINT MOD_UK_FOLDERS_PARENT_NAME UNIQUE (PARENT_ID, NAME),
    CONSTRAINT MOD_FK_FOLDERS_PARENT FOREIGN KEY (PARENT_ID) REFERENCES MOD_FOLDERS(ID)
);

CREATE INDEX MOD_IDX_FOLDERS_PARENT ON MOD_FOLDERS (PARENT_ID);

CREATE TABLE MOD_PROJECT_MEMBERS (
    ID VARCHAR2(36 CHAR) NOT NULL PRIMARY KEY,
    PROJECT_ID VARCHAR2(36 CHAR) NOT NULL,
    -- USER | GROUP
    MEMBER_TYPE VARCHAR2(10 CHAR) NOT NULL,
    MEMBER_ID VARCHAR2(255 CHAR) NOT NULL,
    -- PROJECT_ADMIN | EDITOR | VIEWER
    MEMBER_ROLE VARCHAR2(30 CHAR) NOT NULL,
    CREATED TIMESTAMP,
    CREATED_BY VARCHAR2(100 CHAR),
    UPDATED TIMESTAMP,
    UPDATED_BY VARCHAR2(100 CHAR),
    CONSTRAINT MOD_UK_PROJECT_MEMBERS UNIQUE (PROJECT_ID, MEMBER_TYPE, MEMBER_ID),
    CONSTRAINT MOD_FK_PROJECT_MEMBERS_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES MOD_FOLDERS(ID) ON DELETE CASCADE
);

CREATE INDEX MOD_IDX_PROJECT_MEMBERS_MEMBER ON MOD_PROJECT_MEMBERS (MEMBER_TYPE, MEMBER_ID);

CREATE TABLE MOD_PROCESSES_DIAGRAMS (
    ID VARCHAR2(36) PRIMARY KEY,
    NAME VARCHAR2(255),
    PROCESSKEY VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(150),
    CREATED TIMESTAMP,
    UPDATED TIMESTAMP,
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    TYPE VARCHAR2(50) NOT NULL,
    VERSION NUMBER(10,0) DEFAULT 1,
    DIAGRAM BLOB,
    UPDATED_BY VARCHAR2(100 CHAR),
    FOLDER_ID VARCHAR2(36 CHAR),
    CONSTRAINT MOD_FK_DIAGRAMS_FOLDER FOREIGN KEY (FOLDER_ID) REFERENCES MOD_FOLDERS(ID)
);

CREATE TABLE MOD_REVINFO (
    REV NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    REVTSTMP NUMBER(19)
);

CREATE TABLE MOD_PROCESSES_DIAGRAMS_AUD (
    ID VARCHAR2(36) NOT NULL,
    NAME VARCHAR2(255),
    PROCESSKEY VARCHAR2(100),
    DESCRIPTION VARCHAR2(150),
    CREATED TIMESTAMP,
    UPDATED TIMESTAMP,
    ACTIVE NUMBER(1) DEFAULT 1,
    TYPE VARCHAR2(50),
    VERSION NUMBER(11) DEFAULT 1,
    DIAGRAM_MOD NUMBER(1) DEFAULT 0,
    DIAGRAM BLOB,
    UPDATED_BY VARCHAR2(100 CHAR),
    REV NUMBER(19) NOT NULL,
    REVTYPE NUMBER(6,0),
    CONSTRAINT MOD_PK_RESOURCES_AUD PRIMARY KEY (ID, REV),
    CONSTRAINT MOD_FK_RESOURCES_AUD_REV FOREIGN KEY (REV) REFERENCES MOD_REVINFO(REV)
);

CREATE TABLE MOD_USER_SESSIONS (
    ID VARCHAR2(36) PRIMARY KEY,
    USER_ID VARCHAR2(100 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP
);

CREATE TABLE MOD_DIAGRAM_USAGE (
    ID VARCHAR2(36) PRIMARY KEY,
    USER_ID VARCHAR2(100 CHAR) NOT NULL,
    DIAGRAM_ID VARCHAR2(36) NOT NULL,
    SESSION_ID VARCHAR2(36) NOT NULL,
    OPENED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CLOSED_AT TIMESTAMP,
    CONSTRAINT MOD_FK_DIAGRAM_USAGE_DIAGRAM FOREIGN KEY (DIAGRAM_ID) REFERENCES MOD_PROCESSES_DIAGRAMS(ID) ON DELETE CASCADE,
    CONSTRAINT MOD_FK_DIAGRAM_USAGE_SESSION FOREIGN KEY (SESSION_ID) REFERENCES MOD_USER_SESSIONS(ID) ON DELETE CASCADE
);

CREATE TABLE MOD_FORMS (
    ID VARCHAR2(36 CHAR) PRIMARY KEY,
    DESCRIPTION VARCHAR2(150 CHAR),
    CREATED TIMESTAMP,
    UPDATED TIMESTAMP,
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    FORM_SCHEMA BLOB NOT NULL,
    FORMID VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    VERSION NUMBER(11) DEFAULT 1,
    UPDATED_BY VARCHAR2(100 CHAR),
    FOLDER_ID VARCHAR2(36 CHAR),
    CONSTRAINT MOD_FK_FORMS_FOLDER FOREIGN KEY (FOLDER_ID) REFERENCES MOD_FOLDERS(ID)
);

CREATE TABLE MOD_FORMS_AUD (
    ID VARCHAR2(36) NOT NULL,
    DESCRIPTION VARCHAR2(150),
    CREATED TIMESTAMP,
    UPDATED TIMESTAMP,
    ACTIVE NUMBER(1) DEFAULT 1,
    FORM_SCHEMA BLOB,
    FORMID VARCHAR2(100),
    VERSION NUMBER(11) DEFAULT 1,
    SCHEMA_MOD NUMBER(1) DEFAULT 0,
    UPDATED_BY VARCHAR2(100 CHAR),
    REV NUMBER(19) NOT NULL,
    REVTYPE NUMBER(6,0),
    CONSTRAINT MOD_PK_FORMS_AUD PRIMARY KEY (ID, REV),
    CONSTRAINT MOD_FK_FORMS_AUD_REV FOREIGN KEY (REV) REFERENCES MOD_REVINFO(REV)
);

CREATE TABLE MOD_FORM_USAGE (
    ID VARCHAR2(36) PRIMARY KEY,
    USER_ID VARCHAR2(100 CHAR) NOT NULL,
    FORM_ID VARCHAR2(36) NOT NULL,
    SESSION_ID VARCHAR2(36) NOT NULL,
    OPENED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CLOSED_AT TIMESTAMP,
    CONSTRAINT MOD_FK_FORM_USAGE_FORM FOREIGN KEY (FORM_ID) REFERENCES MOD_FORMS(ID) ON DELETE CASCADE,
    CONSTRAINT MOD_FK_FORM_USAGE_SESSION FOREIGN KEY (SESSION_ID) REFERENCES MOD_USER_SESSIONS(ID) ON DELETE CASCADE
);

CREATE TABLE CHAT_MESSAGES (
    ID           VARCHAR2(36)  NOT NULL,
    ROOM_ID      VARCHAR2(255) NOT NULL,
    ELEMENT_ID   VARCHAR2(255),
    USER_ID      VARCHAR2(255) NOT NULL,
    DISPLAY_NAME VARCHAR2(255),
    CONTENT      CLOB          NOT NULL,
    CREATED_AT   TIMESTAMP     NOT NULL,
    EDITED_AT    TIMESTAMP,
    DELETED_AT   TIMESTAMP,
    CONSTRAINT CHAT_PK_MESSAGES PRIMARY KEY (ID)
);

CREATE INDEX CHAT_IDX_MESSAGES_ROOM_CREATED    ON CHAT_MESSAGES (ROOM_ID, CREATED_AT);
CREATE INDEX CHAT_IDX_MESSAGES_ROOM_EL_CREATED ON CHAT_MESSAGES (ROOM_ID, ELEMENT_ID, CREATED_AT);

CREATE TABLE CHAT_PRESENCE (
    ROOM_ID      VARCHAR2(255) NOT NULL,
    USER_ID      VARCHAR2(255) NOT NULL,
    DISPLAY_NAME VARCHAR2(255),
    LAST_SEEN    TIMESTAMP     NOT NULL,
    CONSTRAINT CHAT_PK_PRESENCE PRIMARY KEY (ROOM_ID, USER_ID)
);

-- Notifications: messages administrators publish to logged-in webclient users (CIB7-1867)
CREATE TABLE NOTIF_NOTIFICATIONS (
    ID           VARCHAR2(36)   NOT NULL,
    TITLE        VARCHAR2(255)  NOT NULL,
    BODY         CLOB NOT NULL,
    -- INFO | WARNING | CRITICAL
    SEVERITY     VARCHAR2(20)   NOT NULL,
    -- ALL | GROUPS (for GROUPS, the groups are in NOTIF_GROUPS)
    AUDIENCE     VARCHAR2(20)   NOT NULL,
    VALID_FROM   TIMESTAMP NOT NULL,
    VALID_TO     TIMESTAMP,
    DISMISSIBLE  NUMBER(1) DEFAULT 1 NOT NULL,
    LINK         VARCHAR2(1000),
    ACTIVE       NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(255)  NOT NULL,
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   VARCHAR2(255),
    CONSTRAINT NOTIF_PK_NOTIFICATIONS PRIMARY KEY (ID)
);

CREATE INDEX NOTIF_IDX_NOTIFICATIONS_ACTIVE ON NOTIF_NOTIFICATIONS (ACTIVE, VALID_FROM, VALID_TO);

CREATE TABLE NOTIF_GROUPS (
    NOTIFICATION_ID VARCHAR2(36)  NOT NULL,
    GROUP_ID        VARCHAR2(255) NOT NULL,
    CONSTRAINT NOTIF_PK_GROUPS PRIMARY KEY (NOTIFICATION_ID, GROUP_ID),
    CONSTRAINT NOTIF_FK_GROUPS_NOTIFICATION FOREIGN KEY (NOTIFICATION_ID) REFERENCES NOTIF_NOTIFICATIONS (ID) ON DELETE CASCADE
);

CREATE INDEX NOTIF_IDX_GROUPS_GROUP ON NOTIF_GROUPS (GROUP_ID);

